  function since(lastSeen, list) {
    const all = list || CHANGELOG;
    if (!lastSeen) return all.slice(0, 2);          // نصب تازه: تازه‌ترین‌ها کافی است
    return all.filter((e) => compare(e.version, lastSeen) > 0);
  }

  /** بالاترین نسخهٔ موجود در تاریخچه */
